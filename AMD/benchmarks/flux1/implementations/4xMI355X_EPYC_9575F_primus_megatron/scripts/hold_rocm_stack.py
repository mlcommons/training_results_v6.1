"""Keep the base image's ROCm builds of torch / TransformerEngine / Triton in place.

The base image ships ROCm-specific builds of these packages that no public index carries.
A dependency resolution that "upgrades" one of them (aiter's dependencies can pull a newer
Triton, for example) produces an image whose first import fails. This helper:

  record <constraints-file> <baseline-file>
      writes a pip constraints file pinning the installed public versions (Triton is watched
      but not constrained: its local version label is not resolvable on an index), and a
      baseline of the exact installed versions;
  check <baseline-file> <stage>
      fails the build if any held package changed during <stage>.
"""
import importlib.metadata as md
import json
import sys

from packaging.version import Version

HELD = (
    "torch",
    "transformer_engine",
    "transformer_engine_rocm7",
    "transformer_engine_rocm10",
    "transformer_engine_rocm_torch",
    "triton",
)
UNCONSTRAINABLE = {"triton"}


def installed():
    out = {}
    for name in HELD:
        try:
            out[name] = md.version(name)
        except md.PackageNotFoundError:
            out[name] = None
    return out


def record(constraints_path, baseline_path):
    versions = installed()
    with open(constraints_path, "w") as f:
        f.write("# Generated by hold_rocm_stack.py: keep the base image's ROCm builds.\n")
        for name, version in versions.items():
            if version is not None and name not in UNCONSTRAINABLE:
                f.write(f"{name}=={Version(version).public}\n")
    with open(baseline_path, "w") as f:
        json.dump(versions, f, indent=1)
    print(f"[hold_rocm_stack] baseline: {versions}")


def check(baseline_path, stage):
    with open(baseline_path) as f:
        baseline = json.load(f)
    now = installed()
    if now != baseline:
        print(f"[hold_rocm_stack] ERROR: held packages changed during {stage}", file=sys.stderr)
        print(f"  before: {baseline}\n  after:  {now}", file=sys.stderr)
        sys.exit(1)
    print(f"[hold_rocm_stack] {stage}: held packages unchanged")


if __name__ == "__main__":
    if sys.argv[1] == "record":
        record(sys.argv[2], sys.argv[3])
    elif sys.argv[1] == "check":
        check(sys.argv[2], sys.argv[3])
    else:
        raise SystemExit(__doc__)
