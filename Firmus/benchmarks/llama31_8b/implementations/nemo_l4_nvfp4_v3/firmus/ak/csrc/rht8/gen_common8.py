"""gen_common8.py (Llama 3.1 8B campaign, 2026-10-08, rx26): writes ak_rht8_common.cuh -- rhtdev's ak_rht_common.cuh
(TE's NVFP4 row + column-RHT cast copied verbatim, the shared storage and the launch_v the instantiation files
instantiate) in its own namespace ak_rht8, including variants8.cuh, with the shared storage extended by the two 256-entry
reciprocal-scale tables of bit 256 (2 KB; the struct then takes 232,432 of the 232,448 bytes a CTA may use) and the
launcher renamed launch_v8 (variants only: no TE-verbatim kVar 0).  Every edit is an exact substitution.
Usage: python3 gen_common8.py <rhtdev/ak_rht_common.cuh> <ak_rht8_common.cuh>"""
import argparse

_ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
_ap.add_argument("src")
_ap.add_argument("out")
_args = _ap.parse_args()
src, out = _args.src, _args.out
T = open(src).read()


def sub(text, a, b, n=1):
    c = text.count(a)
    assert c == n, (c, a[:160])
    return text.replace(a, b)


T = sub(T, "#pragma once\n// ak_rht_common.cuh (Llama 3.1 8B kernel campaign, 2026-10-07; from ak_l8b_rht.cu)",
        "#pragma once\n// ak_rht8_common.cuh: generated by gen_common8.py (rx26, 2026-10-08) from rhtdev's ak_rht_common.cuh\n"
        "// (Llama 3.1 8B kernel campaign, 2026-10-07; from ak_l8b_rht.cu)")
T = sub(T, "namespace ak_rht {\n", "namespace ak_rht8 {\n", n=2)
T = sub(T, "}  // namespace ak_rht\n", "}  // namespace ak_rht8\n", n=2)
T = sub(T, "  uint32_t tmem_base_ptr;\n};",
        "  uint32_t tmem_base_ptr;\n"
        "  alignas(16) float ak_tbl[2][256];   // rx26 bit 256: per CTA, the column and the row path's reciprocal scales\n"
        "};")
T = sub(T, '#include "variants.cuh"', '#include "variants8.cuh"')
T = sub(T, "// ---- the launcher every instantiation file instantiates (binding2's launch_v)",
        "// ---- the launcher the RN instantiation files instantiate (binding8's rht_cast_v)")
T = sub(T, "void launch_v(int64_t m, int64_t n,", "void launch_v8(int64_t m, int64_t n,")
old = T[T.index("  if constexpr (kVar == 0) {\n    detail::row_col_rht_gemm_ntt_w_sfc<"):T.index("  } else {\n    detail::row_col_rht_gemm_ntt_w_sfc_v<")]
T = sub(T, old + "  } else {\n    detail::row_col_rht_gemm_ntt_w_sfc_v<",
        "  static_assert(kVar != 0, \"rx26: variants only\");\n  {\n    detail::row_col_rht_gemm_ntt_w_sfc_v8<")
open(out, "w").write(T)
print("wrote %s (%d lines)" % (out, T.count("\n")))
