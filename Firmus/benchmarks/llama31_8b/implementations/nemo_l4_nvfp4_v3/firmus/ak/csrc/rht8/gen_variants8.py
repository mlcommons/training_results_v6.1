"""gen_variants8.py (Llama 3.1 8B campaign, 2026-10-08, rx26): writes variants8.cuh -- rhtdev's variants.cuh (TE's
row_col_rht_gemm_device with the exactness-preserving bits 1-64 of gen_variants.py) in its own namespace ak_rht8, the
kernel and launcher renamed *_v8, with two more bits that remove instructions from the epilogue warps and change no byte:

  bit 7 (128): the stochastic-rounding draws of a k-tile with the work they share computed once.  TE's counter for draw
      v of a k-tile is (x + v, y, z, w) -- x, y the call's Philox offset (the same in every thread), z, w the thread's
      subsequence -- whenever x + v cannot wrap.  Then, of the three rounds' six 32x32 multiplies per draw, round 1's
      M1 * z and round 2's M0 * (hi(M1 z) ^ y ^ k0) are the same for every draw of the k-tile, and round 1's M0 * (x + v)
      is the same in every thread (computed by the compiler on the uniform datapath): three multiplies per draw are
      left, with the same values, so the same bits.  The branch is taken on x <= 0xFFFFFFF8 (no draw of a k-tile can
      wrap, row path 4 draws, column path 8), the same in every thread of the launch; otherwise the k-tile runs the
      variant's own draw (bits 8 / 32), so a call at a 2^32 boundary of the offset gets the full 128-bit counter add.
  bit 8 (256): the per-16-element block's reciprocal scale from a table.  TE computes, per block,
      min(1 / (float(e4m3 scale) * decode), FLT_MAX) -- an e4m3 -> fp32 conversion, a multiply, an IEEE division (a
      reciprocal with its range check and slow path) and a min.  The value depends only on the scale's byte and the
      call's decode scale, so each epilogue warp group builds the 256 entries once per CTA with exactly those operations
      (the column path from the post-RHT amax, the row path from the pre-RHT amax) into shared memory, and a block
      reads its entry by its scale byte.

  bit 9 (512): bit 128's draws with the branch taken once per launch instead of per k-tile: each epilogue warp
      group's whole work loop is instantiated twice (fast draws / the variant's own draws, chosen at compile time
      inside) and the launch-wide x <= 0xFFFFFFF8 picks one -- with bit 128 alone the compiler if-converts the
      per-k-tile branch and computes both paths' draws (dev rx26a: v207 slower than v79).

Usage: python3 gen_variants8.py <rhtdev/variants.cuh> <variants8.cuh>"""
