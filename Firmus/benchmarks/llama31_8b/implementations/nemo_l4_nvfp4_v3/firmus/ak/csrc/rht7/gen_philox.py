"""gen_philox.py (Llama 3.1 8B campaign, 2026-10-07, NVFP4P version 14): writes philox_variant.cuh -- the RHT cast of
variants.cuh (TE's row_col_rht_gemm_device as rescheduled by gen_variants.py, kernel and launcher) taking the CUDA
generator's Philox state by value instead of a device pointer to (seed, offset): version 12's binding launches a
one-thread kernel (unpack_philox_kernel2) before every stochastic-rounding cast to write at::cuda::philox::unpack(state)
into a two-element tensor that the cast's epilogue warps then read; here those warps call the same unpack themselves
(it reads the captured offset through the graph's pointer, as that kernel does).  The same seed and offset reach the
same Philox draws; nothing else changes.

Every edit is an exact text substitution that must match the given number of times.
Usage: python3 gen_philox.py <variants.cuh> <philox_variant.cuh>"""
import argparse

_ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
_ap.add_argument("src")
_ap.add_argument("out")
_args = _ap.parse_args()
src, out = _args.src, _args.out
T = open(src).read()
k0 = T.index("template <class MShape, class NShape, class KShape, class ClusterShape, class ClusterTileShape,")
k1 = T.index("} // NOLINT(readability/fn_size)") + len("} // NOLINT(readability/fn_size)")
l0 = T.index("template <bool kEnableStochasticRounding, bool kEnableRHTColQuant, bool kEnableRowQuant, bool kEnableSwizzleSFOutput,")
l1 = T.rindex("}  // namespace detail")
kern, launch = T[k0:k1], T[l0:l1].rstrip() + "\n"


def sub(text, a, b, n=1):
    c = text.count(a)
    assert c == n, (c, a[:120])
    return text.replace(a, b)


kern = sub(kern, "row_col_rht_gemm_device_v(", "row_col_rht_gemm_device_vp(")
kern = sub(kern, "    const size_t* rng_state) {", "    at::PhiloxCudaState ak_philox) {")
kern = sub(kern,
           "        rng_seed = rng_state != nullptr ? __ldg(rng_state) : 0;\n"
           "        rng_offset = rng_state != nullptr ? __ldg(rng_state + 1) : 0;\n",
           "        const auto ak_s = at::cuda::philox::unpack(ak_philox);   // version 12's unpack_philox_kernel2, here\n"
           "        rng_seed = static_cast<size_t>(static_cast<int64_t>(std::get<0>(ak_s)));\n"
           "        rng_offset = static_cast<size_t>(static_cast<int64_t>(std::get<1>(ak_s)));\n", n=2)
assert "rng_state" not in kern, "a use of rng_state left"
launch = sub(launch, "void row_col_rht_gemm_ntt_w_sfc_v(", "void row_col_rht_gemm_ntt_w_sfc_vp(")
launch = sub(launch, "    const size_t* rng_state,\n", "    at::PhiloxCudaState ak_philox,\n")
launch = sub(launch, "  auto* kernel_ptr = &row_col_rht_gemm_device_v<", "  auto* kernel_ptr = &row_col_rht_gemm_device_vp<")
launch = sub(launch, "     mma, a_global_amax, d_global_amax, rng_state);", "     mma, a_global_amax, d_global_amax, ak_philox);")
assert "rng_state" not in launch, "a use of rng_state left in the launcher"
head = '''// philox_variant.cuh: generated by gen_philox.py from variants.cuh (see its docstring) -- the RHT cast taking the
// generator's Philox state by value (NVFP4P version 14).
namespace ak_rht {
namespace detail {

'''
tail = '''
}  // namespace detail
}  // namespace ak_rht
'''
open(out, "w").write(head + kern + "\n\n" + launch + tail)
print("wrote %s: kernel %d lines, launcher %d lines" % (out, kern.count("\n"), launch.count("\n")))
