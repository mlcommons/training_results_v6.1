"""gen_ext.py: writes ak_l8b_rht.cu = TE's row_cast_col_hadamard_transform_cast_fusion.cu kernel and launcher, verbatim,
in namespace ak_rht::detail, plus a torch binding and our variants (appended from variants.cuh).
Usage: python3 gen_ext.py <TE .cu> <out .cu>"""
import argparse
_ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
_ap.add_argument("src")
_ap.add_argument("out")
_args = _ap.parse_args()
src, out = _args.src, _args.out
L = open(src).read().split("\n")
# TE's file: includes (lines 7-39), then namespace transformer_engine { namespace detail { namespace { (43-45)
# ... kernel + launcher up to the closing of row_col_rht_gemm_ntt_w_sfc (line 1218), then the namespace closes (1220-1221)
start = next(i for i, l in enumerate(L) if l.startswith("using namespace cute;"))
end = next(i for i, l in enumerate(L) if l.startswith("}  // namespace") and i > start)
body = L[start:end]
assert any("row_col_rht_gemm_device(" in l for l in body) and any("void row_col_rht_gemm_ntt_w_sfc(" in l for l in body)
incs = [l for l in L[:start] if l.startswith("#include")]
hdr = """// ak_l8b_rht.cu (Llama 3.1 8B kernel campaign, 2026-10-07): TE's NVFP4 row-wise cast + column-wise 16-token RHT cast
// (transformer_engine/common/hadamard_transform/row_cast_col_hadamard_transform_cast_fusion.cu, row_col_rht_gemm_device
// and its launcher row_col_rht_gemm_ntt_w_sfc) copied verbatim into namespace ak_rht::detail, so the same instructions
// can be built, timed and varied outside TE.  Generated by gen_ext.py; the binding and the variants follow the copy.
// Built for sm_103a with TE's flags for this file (-O3 --expt-relaxed-constexpr, NVTE_BUILD_NUM_PHILOX_ROUNDS=3, no
// fast math).
#include <torch/extension.h>
#include <ATen/cuda/CUDAContext.h>
#include <ATen/cuda/CUDAGeneratorImpl.h>
#include <ATen/cuda/CUDAGraphsUtils.cuh>
#include <c10/cuda/CUDAGuard.h>
#include <mutex>
"""
parts = [hdr] + incs + ["", "// clang-format off", "namespace ak_rht {", "namespace detail {",
         "namespace ptx = ::transformer_engine::ptx;  // TE's arch macros name ptx:: unqualified", ""] + body + \
        ["", "}  // namespace detail", "}  // namespace ak_rht", "// clang-format on", "",
         '#include "variants.cuh"', '#include "binding.cuh"', ""]
open(out, "w").write("\n".join(parts))
print("wrote", out, len(body), "lines of TE's code")
